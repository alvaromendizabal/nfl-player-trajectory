"""Synthetic-only full-path regression; never invoked by the production launcher.

Requires a synthetic Round 4 fixture generated by its original integration test.
The earlier gate is injected ONLY into synthetic fixture reports to cover the
continuation branch; no synthetic metric is presented as feature-value evidence.
Private inputs are not used. Identity checks use fixture-specific hashes; the
production CLI has no skip-identity flag.
"""
from pathlib import Path
import json
import shutil
import subprocess
import sys
import numpy as np

KIT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(KIT))
from confirmation import context,signature,replay_discovery,prepare,run_fold,summarize
from parent_support import digest,atomic_json


def event(name,**kw):print(name,kw,flush=True)


def configure(root, old_kit):
    newkit=root/'round5_kit';newkit.mkdir(exist_ok=True)
    for p in KIT.glob('*.py'):shutil.copy2(p,newkit/p.name)
    shutil.copy2(root/'fixture_contract.json',newkit/'parent_contract.json')
    c=json.loads((KIT/'input_contract.json').read_text())
    # Only this synthetic gate annotation is injected, not scores/predictions.
    for n in ['summary.json','replay.json']:
        p=root/'out'/n;r=json.loads(p.read_text())
        r['contrasts'][0]['screen_gate']=True
        r['fixture_continuation_authorization_injected']=True
        atomic_json(p,r)
    r=json.loads((root/'out/summary.json').read_text())
    c.update(round4_source_signature=r['source_signature'],round4_experiment_signature=r['experiment_signature'],
             round4_metrics=r['pooled_rmse'],
             round4_report_hashes={n:digest(root/'out'/n) for n in ['summary.json','replay.json','preparation.json']},
             round4_source_hashes={p.name:digest(p) for p in old_kit.glob('*.py')},
             round4_contract_sha256=digest(old_kit/'input_contract.json'))
    atomic_json(newkit/'input_contract.json',c)
    atomic_json(root/'round5_fixture_paths.json',{'old_kit':str(old_kit)})
    (root/'round5_out').mkdir(exist_ok=True)


def get_context(root):
    paths=json.loads((root/'round5_fixture_paths.json').read_text())
    return context(root/'round5_kit',root/'out',Path(paths['old_kit']),root/'parent',
                   root/'legacy',root/'repo',verify_identity=False)


def run(root, stage):
    ctx=get_context(root);out=root/'round5_out';sig=signature(ctx)
    if stage=='preflight':
        _,rec=replay_discovery(ctx)
        result={'status':'temporal_preflight_passed','signature':sig,'parent_replay':rec,
                'fold_populations':ctx['populations'],'synthetic_only':True}
        atomic_json(out/'preflight.json',result);return result
    if stage in ('smoke','prepare'):
        return prepare(ctx,root/'repo',out,sig,smoke=stage=='smoke',event=event)
    if stage in ('fit2','fit3'):
        return run_fold(ctx,out,sig,int(stage[-1]))
    if stage=='replay':
        _,rec=replay_discovery(ctx)
        rr=[run_fold(ctx,out,sig,f,replay_only=True) for f in (2,3)]
        assert all(r['new_coordinate_models']==0 for r in rr)
        result={'status':'temporal_replay_exact','signature':sig,'completed_later_folds':[2,3],
                'new_coordinate_models':0,'old_models_refitted':0,'parent_replay':rec,'new_models_replayed':8,'synthetic_only':True}
        atomic_json(out/'replay.json',result)
        return summarize(ctx,out,sig)
    if stage=='summarize':return summarize(ctx,out,sig)
    if stage=='report':
        from run_round import export_report
        return str(export_report(out))
    raise ValueError(stage)


def main():
    root=Path(sys.argv[1]);stage=sys.argv[2]
    if stage=='configure':configure(root,Path(sys.argv[3]));return
    if stage!='all':
        result=run(root,stage);print(json.dumps(result));return
    original={str(p):(digest(p),p.stat().st_mtime_ns) for folder in ('repo','parent','legacy','out') for p in (root/folder).rglob('*') if p.is_file()}
    run(root,'preflight');sm=run(root,'smoke');a=run(root,'prepare');b=run(root,'prepare')
    assert sm['raw_feature_plays_rebuilt']==32 and b['new_checkpoints']==0
    assert a['round4_checkpoints_reused']==40 and a['new_checkpoints']==24
    first=run(root,'fit2');second=run(root,'fit3')
    assert first['new_coordinate_models']==4 and second['new_coordinate_models']==4
    checkpoints={str(p):(digest(p),p.stat().st_mtime_ns) for p in (root/'round5_out').rglob('*.pkl')}
    subprocess.run([sys.executable,str(Path(__file__).resolve()),str(root),'replay'],check=True,timeout=60)
    assert all((digest(Path(p)),Path(p).stat().st_mtime_ns)==v for p,v in original.items())
    assert all((digest(Path(p)),Path(p).stat().st_mtime_ns)==v for p,v in checkpoints.items())
    rec={'synthetic_only':True,'private_NFL_data_used':False,'new_coordinate_models':8,
         'old_models_refitted':0,'old_coordinate_models_replayed':4,'new_model_forward_replay_exact':True,
         'fresh_process_replay_new_fits':0,'parent_files_bytes_and_mtimes_unchanged':True,
         'new_weight_bytes_and_mtimes_unchanged_on_replay':True,'state_checkpoints_reused_from_round4':40,
         'new_state_checkpoints':24,'smoke_raw_parity_plays':32,
         'fixture_gate_annotation_injected_for_branch_coverage':True,
         'float32_and_float64_shards_exercised':True}
    atomic_json(root/'round5_integration.json',rec);print(json.dumps(rec))

if __name__=='__main__':main()
